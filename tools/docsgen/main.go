// Command docsgen renders one Markdown page per diagnostic code from the registry.
//
// Usage: docsgen [-out docs/diagnostics] [-check]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/HarnageaGabriel/trasloco/internal/diag"
)

func main() {
	out := flag.String("out", "docs/diagnostics", "output directory")
	check := flag.Bool("check", false, "fail if generated output differs from files on disk")
	flag.Parse()
	if err := run(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, "docsgen:", err)
		os.Exit(1)
	}
}

func run(out string, check bool) error {
	if err := diag.RegistryError(); err != nil {
		return err
	}
	pages := render(diag.List())
	if check {
		return verify(out, pages)
	}
	return write(out, pages)
}

// render returns file name -> content, deterministically.
func render(entries []diag.Entry) map[string][]byte {
	pages := make(map[string][]byte, len(entries)+1)
	sorted := append([]diag.Entry(nil), entries...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Code < sorted[j].Code })
	var index bytes.Buffer
	index.WriteString("<!-- Code generated by tools/docsgen; DO NOT EDIT. -->\n\n# Diagnostic codes\n\n| Code | Severity | Title | Status |\n|---|---|---|---|\n")
	for _, entry := range sorted {
		fmt.Fprintf(&index, "| [%s](%s.md) | %s | %s | %s |\n", entry.Code, entry.Code, entry.Severity, cell(entry.Title), entry.Status)
		pages[entry.Code+".md"] = []byte(page(entry))
	}
	pages["README.md"] = index.Bytes()
	return pages
}

func cell(value string) string { return strings.ReplaceAll(value, "|", `\|`) }

func page(entry diag.Entry) string {
	var b strings.Builder
	b.WriteString("<!-- Code generated by tools/docsgen; DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&b, "# %s: %s\n\n", entry.Code, entry.Title)
	fmt.Fprintf(&b, "- Severity: %s\n- Exit class: %s\n- Area: %s\n- Since: %s\n- Status: %s\n", entry.Severity, entry.ExitClass, entry.Area, entry.Since, entry.Status)
	if entry.Fidelity != nil {
		fmt.Fprintf(&b, "- Fidelity: %s\n", *entry.Fidelity)
	}
	if entry.Provenance != nil {
		fmt.Fprintf(&b, "- Provenance: %s\n", *entry.Provenance)
	}
	if entry.ReplacedBy != nil && *entry.ReplacedBy != "" {
		fmt.Fprintf(&b, "- Replaced by: [%s](%s.md)\n", *entry.ReplacedBy, *entry.ReplacedBy)
	}
	fmt.Fprintf(&b, "\n## Remediation\n\n%s\n\n## Example\n\n```json\n%s\n```\n", entry.Remediation, example(entry))
	if len(entry.History) > 0 {
		b.WriteString("\n## History\n\n")
		for _, h := range entry.History {
			fmt.Fprintf(&b, "- %s: %s\n", h.Version, h.Change)
		}
	}
	return b.String()
}

func example(entry diag.Entry) string {
	var params strings.Builder
	for i, name := range entry.Params {
		if i > 0 {
			params.WriteString(", ")
		}
		fmt.Fprintf(&params, "%q: %q", name, "<"+name+">")
	}
	return fmt.Sprintf(`{"code": %q, "severity": %q, "params": {%s}}`, entry.Code, entry.Severity, params.String())
}

func write(out string, pages map[string][]byte) error {
	if err := os.MkdirAll(out, 0o700); err != nil {
		return err
	}
	existing, err := filepath.Glob(filepath.Join(out, "*.md"))
	if err != nil {
		return err
	}
	for _, path := range existing {
		if _, ok := pages[filepath.Base(path)]; !ok {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	for name, content := range pages {
		if err := os.WriteFile(filepath.Join(out, name), content, 0o600); err != nil {
			return err
		}
	}
	return nil
}

func verify(out string, pages map[string][]byte) error {
	var drift []string
	for name, content := range pages {
		got, err := os.ReadFile(filepath.Join(out, name)) //nolint:gosec // generated file names, trusted output dir
		if err != nil || !bytes.Equal(normalize(got), content) {
			drift = append(drift, name)
		}
	}
	existing, _ := filepath.Glob(filepath.Join(out, "*.md"))
	for _, path := range existing {
		if _, ok := pages[filepath.Base(path)]; !ok {
			drift = append(drift, filepath.Base(path)+" (stale)")
		}
	}
	if len(drift) > 0 {
		sort.Strings(drift)
		return fmt.Errorf("generated docs out of date (run `make docs`): %s", strings.Join(drift, ", "))
	}
	return nil
}

func normalize(data []byte) []byte { return bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n")) }
