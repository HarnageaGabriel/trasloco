package main

import (
	"context"
	"flag"
	"fmt"
	"html"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	catalogmodel "github.com/HarnageaGabriel/trasloco/internal/catalog"
)

const retirementURL = "https://learn.microsoft.com/en-us/azure/devops/pipelines/tasks/task-retirement"

const (
	tableRowPattern  = `(?is)<tr\b[^>]*>(.*?)</tr>`
	tableCellPattern = `(?is)<t[dh]\b[^>]*>(.*?)</t[dh]>`
	htmlTagPattern   = `(?s)<[^>]*>`
	taskNamePattern  = `\b([A-Za-z][A-Za-z0-9_.-]*)@([0-9]+)\b`
)

func runRetirement(ctx context.Context, args []string) error {
	flags := flag.NewFlagSet("retirement", flag.ContinueOnError)
	src := flags.String("src", "", "local saved official retirement page")
	out := flags.String("out", "catalog/azure-pipelines/tasks.retirement.yaml", "output file")
	pageURL := flags.String("url", retirementURL, "official retirement page URL")
	if err := flags.Parse(args); err != nil {
		return err
	}
	var data []byte
	var err error
	if *src != "" {
		data, err = os.ReadFile(*src)
	} else {
		client := newHTTPClient("", *pageURL)
		data, _, err = client.get(ctx, *pageURL)
	}
	if err != nil {
		return err
	}
	retired, err := parseRetirementHTML(data)
	if err != nil {
		return err
	}
	result := catalogmodel.RetirementFile{
		SchemaVersion: 1, Kind: "task-retirement", Source: catalogmodel.RetirementSource{URL: *pageURL},
		RetirementDate: "2026-10-15", RemovalDate: "2027-03-15", Tasks: retired,
	}
	header := "# Code generated by catalog-gen; DO NOT EDIT.\n# Source: " + *pageURL + "\n"
	return writeYAML(ctx, *out, header, result)
}

func parseRetirementHTML(data []byte) ([]catalogmodel.RetiredTask, error) {
	pageText := plainHTML(data)
	for _, expected := range []string{"October 15, 2026", "March 15, 2027"} {
		if !strings.Contains(pageText, expected) {
			return nil, fmt.Errorf("official retirement page does not contain expected date %q", expected)
		}
	}
	tableRowRE := regexp.MustCompile(tableRowPattern)
	tableCellRE := regexp.MustCompile(tableCellPattern)
	byRef := make(map[string]catalogmodel.RetiredTask)
	for _, row := range tableRowRE.FindAllSubmatch(data, -1) {
		cells := tableCellRE.FindAllSubmatch(row[1], -1)
		if len(cells) < 1 {
			continue
		}
		retiring := taskRefs(plainHTML(cells[0][1]))
		if len(retiring) == 0 {
			continue
		}
		var replacements []string
		replacementText := make([]string, 0, len(cells)-1)
		for _, cell := range cells[1:] {
			text := plainHTML(cell[1])
			replacementText = append(replacementText, text)
			replacements = append(replacements, taskRefs(text)...)
		}
		replacements = uniqueRefs(replacements)
		kind := "none"
		if len(replacements) > 0 {
			kind = "task"
		} else if text := strings.TrimSpace(strings.Join(replacementText, " ")); text != "" && !strings.EqualFold(text, "none") {
			kind = "external"
		}
		for _, ref := range retiring {
			name, major, _ := strings.Cut(ref, "@")
			majorNumber, _ := strconv.Atoi(major)
			byRef[strings.ToLower(ref)] = catalogmodel.RetiredTask{
				Task: ref, Name: name, Major: majorNumber, ReplacementKind: kind, Replacements: replacements,
			}
		}
	}
	if len(byRef) == 0 {
		return nil, fmt.Errorf("official retirement page contained no TaskName@major table rows")
	}
	keys := make([]string, 0, len(byRef))
	for key := range byRef {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	result := make([]catalogmodel.RetiredTask, 0, len(keys))
	for _, key := range keys {
		result = append(result, byRef[key])
	}
	return result, nil
}

func plainHTML(value []byte) string {
	htmlTagRE := regexp.MustCompile(htmlTagPattern)
	text := html.UnescapeString(htmlTagRE.ReplaceAllString(string(value), " "))
	return strings.Join(strings.Fields(text), " ")
}

func taskRefs(value string) []string {
	taskNameRE := regexp.MustCompile(taskNamePattern)
	matches := taskNameRE.FindAllStringSubmatch(value, -1)
	result := make([]string, 0, len(matches))
	for _, match := range matches {
		result = append(result, match[1]+"@"+match[2])
	}
	sort.Slice(result, func(i, j int) bool { return strings.ToLower(result[i]) < strings.ToLower(result[j]) })
	return result
}

func uniqueRefs(refs []string) []string {
	byKey := make(map[string]string, len(refs))
	for _, ref := range refs {
		byKey[strings.ToLower(ref)] = ref
	}
	keys := make([]string, 0, len(byKey))
	for key := range byKey {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	result := make([]string, 0, len(keys))
	for _, key := range keys {
		result = append(result, byKey[key])
	}
	return result
}
