const (
	tasksRepo = "https://github.com/microsoft/azure-pipelines-tasks"
	tasksSHA  = "f1962f12fac2899b5d689967dda0d25523cc3ec4"
)

type taskBlob struct {
	Path string `json:"path"`
	Type string `json:"type"`
}

func runTasks(ctx context.Context, args []string) error {
	flags := flag.NewFlagSet("tasks", flag.ContinueOnError)
	src := flags.String("src", "", "local azure-pipelines-tasks checkout")
	out := flags.String("out", "catalog/azure-pipelines/tasks.generated.yaml", "output file")
	apiBase := flags.String("api-base", "https://api.github.com", "GitHub API base")
	rawBase := flags.String("raw-base", "https://raw.githubusercontent.com", "raw content base")
	if err := flags.Parse(args); err != nil {
		return err
	}
	var files []namedData
	var err error
	if *src != "" {
		files, err = localTaskFiles(ctx, *src)
	} else {
		files, err = remoteTaskFiles(ctx, *apiBase, *rawBase)
	}
	if err != nil {
		return err
	}
	generated, err := extractTasks(ctx, files)
	if err != nil {
		return err
	}
	header := "# Code generated by catalog-gen; DO NOT EDIT.\n# Source: " + tasksRepo + " @ " + tasksSHA + "\n# License: MIT; see THIRD_PARTY_LICENSES/azure-pipelines-tasks-MIT.txt\n# Facts only: descriptive prose is intentionally excluded.\n"
	return writeYAML(ctx, *out, header, generated)
}

type namedData struct {
	name string
	data []byte
}

func localTaskFiles(ctx context.Context, root string) ([]namedData, error) {
	paths, err := filepath.Glob(filepath.Join(root, "Tasks", "*", "task.json"))
	if err != nil {
		return nil, err
	}
	sort.Strings(paths)
	result := make([]namedData, 0, len(paths))
	for _, name := range paths {
		if err := ctx.Err(); err != nil {
			return nil, err
		}
		if strings.EqualFold(filepath.Base(filepath.Dir(name)), "_generated") {
			continue
		}
		data, err := os.ReadFile(name) // #nosec G304 -- src is an explicit operator-selected pinned checkout.
		if err != nil {
			return nil, err
		}
		result = append(result, namedData{name: filepath.Base(filepath.Dir(name)), data: data})
	}
	return result, nil
}

func remoteTaskFiles(ctx context.Context, apiBase, rawBase string) ([]namedData, error) {
	client := newHTTPClient(os.Getenv("GITHUB_TOKEN"), apiBase)
	url := strings.TrimRight(apiBase, "/") + "/repos/microsoft/azure-pipelines-tasks/git/trees/" + tasksSHA + "?recursive=1"
	data, _, err := client.get(ctx, url)
	if err != nil {
		return nil, err
	}
	var tree struct {
		Tree      []taskBlob `json:"tree"`
		Truncated bool       `json:"truncated"`
	}
	if err := json.Unmarshal(data, &tree); err != nil {
		return nil, fmt.Errorf("decode task tree: %w", err)
	}
	if tree.Truncated {
		return nil, fmt.Errorf("GitHub tree response is truncated")
	}
	var paths []string
	for _, blob := range tree.Tree {
		parts := strings.Split(blob.Path, "/")
		if blob.Type == "blob" && len(parts) == 3 && parts[0] == "Tasks" && parts[1] != "_generated" && parts[2] == "task.json" {
			paths = append(paths, blob.Path)
		}
	}
	sort.Strings(paths)
	result := make([]namedData, len(paths))
	ctx, cancel := context.WithCancel(ctx)
	defer cancel()
	jobs := make(chan int)
	var wg sync.WaitGroup
	var firstErr error
	var errMu sync.Mutex
	for range 8 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for i := range jobs {
				url := strings.TrimRight(rawBase, "/") + "/microsoft/azure-pipelines-tasks/" + tasksSHA + "/" + paths[i]
				body, _, err := client.get(ctx, url)
				if err != nil {
					errMu.Lock()
					if firstErr == nil {
						firstErr = err
						cancel()
					}
					errMu.Unlock()
					continue
				}
				result[i] = namedData{name: strings.Split(paths[i], "/")[1], data: body}
			}
		}()
	}
sendJobs:
	for i := range paths {
		select {
		case jobs <- i:
		case <-ctx.Done():
			break sendJobs
		}
	}
	close(jobs)
	wg.Wait()
	if firstErr != nil {
		return nil, firstErr
	}
	if err := ctx.Err(); err != nil && !errorsIsCanceledBySuccess(err, firstErr) {
		return nil, err
	}
	return result, nil
}

func errorsIsCanceledBySuccess(err, workerErr error) bool {
	return errors.Is(err, context.Canceled) && workerErr != nil
}

func extractTasks(ctx context.Context, files []namedData) (catalogmodel.TasksFile, error) {
	result := catalogmodel.TasksFile{SchemaVersion: 1, Kind: "tasks-generated", Source: catalogmodel.TaskSource{Repo: tasksRepo, Commit: tasksSHA, License: "MIT"}}
	byName := make(map[string]int)
	for _, file := range files {
		if err := ctx.Err(); err != nil {
			return result, err
		}
		var raw map[string]any
		data := bytes.TrimPrefix(file.data, []byte{0xef, 0xbb, 0xbf})
		decoder := json.NewDecoder(bytes.NewReader(data))
		decoder.UseNumber()
		if err := decoder.Decode(&raw); err != nil {
			return result, fmt.Errorf("%s/task.json: %w", file.name, err)
		}
		nameValue, err := requiredTaskValue(raw, "name", file.name)
		if err != nil {
			return result, err
		}
		name := stringValue(nameValue)
		idValue, err := requiredTaskValue(raw, "id", name)
		if err != nil {
			return result, err
		}
		id := strings.ToLower(stringValue(idValue))
		versionValue, err := requiredTaskValue(raw, "version", name)
		if err != nil {
			return result, err
		}
		versionObject, _ := versionValue.(map[string]any)
		major, err := requiredTaskValue(versionObject, "major", name)
		if err != nil {
			return result, err
		}
		minor, err := requiredTaskValue(versionObject, "minor", name)
		if err != nil {
			return result, err
		}
		patch, err := requiredTaskValue(versionObject, "patch", name)
		if err != nil {
			return result, err
		}
		version := catalogmodel.TaskVersion{Major: intValue(major), Minor: intValue(minor), Patch: intValue(patch), Dir: file.name}
		if value, ok, err := taskValue(raw, "deprecated", name); err != nil {
			return result, err
		} else if ok {
			version.Deprecated = boolValue(value)
		}
		_, hasDeprecationMessage, err := taskValue(raw, "deprecationMessage", name)
		if err != nil {
			return result, err
		}
		version.HasDeprecationMessage = hasDeprecationMessage
		if value, ok, err := taskValue(raw, "removalDate", name); err != nil {
			return result, err
		} else if ok {
			version.RemovalDate = stringValue(value)
		}
		if value, ok, err := taskValue(raw, "preview", name); err != nil {
			return result, err
		} else if ok {
			version.Preview = boolValue(value)
		}
		if version.Handlers, err = objectKeys(raw, "execution", name); err != nil {
			return result, err
		}
		if version.PreJobHandlers, err = objectKeys(raw, "prejobexecution", name); err != nil {
			return result, err
		}
		if version.PostJobHandlers, err = objectKeys(raw, "postjobexecution", name); err != nil {
			return result, err
		}
		if version.Groups, err = groupNames(raw, name); err != nil {
			return result, err
		}
		if version.Inputs, err = inputs(raw, name); err != nil {
			return result, err
		}
		key := strings.ToLower(name)
		if index, ok := byName[key]; ok {
			if result.Tasks[index].ID != id {
				return result, fmt.Errorf("task %s has inconsistent ids %s and %s", name, result.Tasks[index].ID, id)
			}
			result.Tasks[index].Versions = append(result.Tasks[index].Versions, version)
		} else {
			byName[key] = len(result.Tasks)
			result.Tasks = append(result.Tasks, catalogmodel.Task{Name: name, ID: id, Versions: []catalogmodel.TaskVersion{version}})
		}
	}
	sort.Slice(result.Tasks, func(i, j int) bool {
		return strings.ToLower(result.Tasks[i].Name) < strings.ToLower(result.Tasks[j].Name)
	})
	for i := range result.Tasks {
		sort.SliceStable(result.Tasks[i].Versions, func(a, b int) bool {
			x, y := result.Tasks[i].Versions[a], result.Tasks[i].Versions[b]
			if x.Major != y.Major {
				return x.Major < y.Major
			}
			return x.Dir < y.Dir
		})
	}
	return result, nil
}

func taskValue(object map[string]any, key, task string) (any, bool, error) {
	value, ok, err := lookup(object, key)
	if err != nil {
		return nil, false, fmt.Errorf("task %s key %q: %w", task, key, err)
	}
	return value, ok, nil
}

func requiredTaskValue(object map[string]any, key, task string) (any, error) {
	value, ok, err := taskValue(object, key, task)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, fmt.Errorf("task %s is missing key %q", task, key)
	}
	return value, nil
}

func objectKeys(raw map[string]any, key, task string) ([]string, error) {
	value, ok, err := taskValue(raw, key, task)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, nil
	}
	object, ok := value.(map[string]any)
	if !ok {
		return nil, nil
	}
	keys := make([]string, 0, len(object))
	for key := range object {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys, nil
}

func groupNames(raw map[string]any, task string) ([]string, error) {
	value, _, err := taskValue(raw, "groups", task)
	if err != nil {
		return nil, err
	}
	rows, _ := value.([]any)
	result := make([]string, 0, len(rows))
	for _, row := range rows {
		if object, ok := row.(map[string]any); ok {
			if name, ok, err := taskValue(object, "name", task); err != nil {
				return nil, err
			} else if ok {
				result = append(result, stringValue(name))
			}
		}
	}
	return result, nil
}

func inputs(raw map[string]any, task string) ([]catalogmodel.Input, error) {
	value, _, err := taskValue(raw, "inputs", task)
	if err != nil {
		return nil, err
	}
	rows, _ := value.([]any)
	result := make([]catalogmodel.Input, 0, len(rows))
	for _, row := range rows {
		object, ok := row.(map[string]any)
		if !ok {
			continue
		}
		name, err := requiredTaskValue(object, "name", task)
		if err != nil {
			return nil, err
		}
		inputType, err := requiredTaskValue(object, "type", task)
		if err != nil {
			return nil, err
		}
		input := catalogmodel.Input{Name: stringValue(name), Type: canonicalType(stringValue(inputType))}
		if value, ok, err := taskValue(object, "aliases", task); err != nil {
			return nil, err
		} else if ok {
			switch aliases := value.(type) {
			case []any:
				for _, alias := range aliases {
					input.Aliases = append(input.Aliases, stringValue(alias))
				}
			case string:
				if aliases != "" {
					input.Aliases = []string{aliases}
				}
			}
		}
		if value, ok, err := taskValue(object, "defaultValue", task); err != nil {
			return nil, err
		} else if ok {
			input.Default = stringValue(value)
			if len([]byte(input.Default)) > 200 {
				input.Default = ""
				input.DefaultOmitted = true
			}
		}
		if value, ok, err := taskValue(object, "required", task); err != nil {
			return nil, err
		} else if ok {
			input.Required = boolValue(value)
		}
		if value, ok, err := taskValue(object, "visibleRule", task); err != nil {
			return nil, err
		} else if ok {
			input.VisibleRule = stringValue(value)
		}
		if value, ok, err := taskValue(object, "groupName", task); err != nil {
			return nil, err
		} else if ok {
			input.Group = stringValue(value)
		}
		if value, ok, err := taskValue(object, "options", task); err != nil {
			return nil, err
		} else if ok {
			switch options := value.(type) {
			case map[string]any:
				for key := range options {
					input.Options = append(input.Options, key)
				}
				sort.Strings(input.Options)
			case []any:
				for _, option := range options {
					input.Options = append(input.Options, stringValue(option))
				}
			}
		}
		result = append(result, input)
	}
	return result, nil
}

func canonicalType(value string) string {
	if strings.EqualFold(value, "multiline") {
		return "multiLine"
	}
	if strings.EqualFold(value, "picklist") {
		return "pickList"
	}
	return value
}
