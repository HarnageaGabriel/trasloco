type gitRef struct {
	Ref    string    `json:"ref"`
	Object gitObject `json:"object"`
}

type gitObject struct {
	Type string `json:"type"`
	SHA  string `json:"sha"`
}

type semanticVersion struct{ major, minor, patch int }

func runActions(ctx context.Context, args []string) error {
	flags := flag.NewFlagSet("actions", flag.ContinueOnError)
	out := flags.String("out", "catalog/github-actions/actions.lock.yaml", "output file")
	apiBase := flags.String("api-base", "https://api.github.com", "GitHub API base")
	rawBase := flags.String("raw-base", "https://raw.githubusercontent.com", "raw content base")
	names := flags.String("names", strings.Join(defaultActionNames(), ","), "comma-separated owner/repo[/path] actions")
	if err := flags.Parse(args); err != nil {
		return err
	}
	actions := splitNames(*names)
	client := newHTTPClient(os.Getenv("GITHUB_TOKEN"), *apiBase)
	lock, err := resolveActions(ctx, client, *apiBase, *rawBase, actions)
	if err != nil {
		return err
	}
	header := "# Code generated by catalog-gen; DO NOT EDIT.\n# Tags resolved through the GitHub Git API; annotated tags are dereferenced.\n"
	return writeYAML(ctx, *out, header, lock)
}

