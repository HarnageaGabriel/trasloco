func splitNames(value string) []string {
	seen := make(map[string]struct{})
	var result []string
	for _, name := range strings.Split(value, ",") {
		name = strings.TrimSpace(name)
		if name == "" {
			continue
		}
		key := strings.ToLower(name)
		if _, ok := seen[key]; ok {
			continue
		}
		seen[key] = struct{}{}
		result = append(result, name)
	}
	sort.Slice(result, func(i, j int) bool { return strings.ToLower(result[i]) < strings.ToLower(result[j]) })
	return result
}

func resolveActions(ctx context.Context, client httpClient, apiBase, rawBase string, names []string) (catalogmodel.ActionsLock, error) {
	result := catalogmodel.ActionsLock{SchemaVersion: 1, Kind: "actions-lock"}
	for _, name := range names {
		if err := ctx.Err(); err != nil {
			return result, err
		}
		parts := strings.Split(name, "/")
		if len(parts) < 2 {
			return result, fmt.Errorf("invalid action name %q", name)
		}
		repository := parts[0] + "/" + parts[1]
		subpath := strings.Join(parts[2:], "/")
		version, object, err := latestTag(ctx, client, apiBase, repository)
		if err != nil {
			return result, fmt.Errorf("resolve %s: %w", name, err)
		}
		sha, err := dereferenceTag(ctx, client, apiBase, repository, object)
		if err != nil {
			return result, fmt.Errorf("resolve %s %s: %w", name, version, err)
		}
		runtime, err := actionRuntime(ctx, client, rawBase, repository, subpath, sha)
		if err != nil {
			return result, fmt.Errorf("read %s %s: %w", name, version, err)
		}
		if !catalogmodel.RuntimeAllowed(runtime) {
			result.Rejected = append(result.Rejected, catalogmodel.RejectedAction{Name: name, Version: version, RunsUsing: runtime})
			continue
		}
		result.Actions = append(result.Actions, catalogmodel.LockedAction{Name: name, Version: version, SHA: sha, RunsUsing: runtime})
	}
	return result, nil
}

func latestTag(ctx context.Context, client httpClient, apiBase, repository string) (string, gitObject, error) {
	refsByName := make(map[string]gitRef)
	endpoint := strings.TrimRight(apiBase, "/") + "/repos/" + repository + "/git/matching-refs/tags/"
	next := endpoint + "?per_page=100"
	for page := 0; next != "" && page < 100; page++ {
		data, headers, err := client.get(ctx, next)
		if err != nil {
			return "", gitObject{}, err
		}
		var pageRefs []gitRef
		if err := json.Unmarshal(data, &pageRefs); err != nil {
			return "", gitObject{}, fmt.Errorf("decode tag refs: %w", err)
		}
		for _, ref := range pageRefs {
			refsByName[ref.Ref] = ref
		}
		next, err = nextLink(next, headers.Get("Link"))
		if err != nil {
			return "", gitObject{}, err
		}
	}
	refs := make([]gitRef, 0, len(refsByName))
	for _, ref := range refsByName {
		refs = append(refs, ref)
	}
	sort.Slice(refs, func(i, j int) bool { return refs[i].Ref < refs[j].Ref })
	var best semanticVersion
	var bestName string
	var bestObject gitObject
	for _, ref := range refs {
		name := strings.TrimPrefix(ref.Ref, "refs/tags/")
		parsed, ok := parseSemver(name)
		if ok && (bestName == "" || parsed.greater(best)) {
			best, bestName, bestObject = parsed, name, ref.Object
		}
	}
	if bestName == "" {
		return "", gitObject{}, errors.New("no stable semantic-version tag found")
	}
	return bestName, bestObject, nil
}

func nextLink(current, header string) (string, error) {
	for _, part := range strings.Split(header, ",") {
		sections := strings.Split(part, ";")
		if len(sections) < 2 || !strings.Contains(strings.Join(sections[1:], ";"), `rel="next"`) {
			continue
		}
		target := strings.TrimSpace(sections[0])
		if len(target) < 2 || target[0] != '<' || target[len(target)-1] != '>' {
			return "", fmt.Errorf("invalid Link next target %q", target)
		}
		base, err := url.Parse(current)
		if err != nil {
			return "", fmt.Errorf("parse current page URL: %w", err)
		}
		link, err := url.Parse(target[1 : len(target)-1])
		if err != nil {
			return "", fmt.Errorf("parse Link next URL: %w", err)
		}
		return base.ResolveReference(link).String(), nil
	}
	return "", nil
}

func parseSemver(value string) (semanticVersion, bool) {
	value = strings.TrimPrefix(value, "v")
	parts := strings.Split(value, ".")
	if len(parts) != 3 {
		return semanticVersion{}, false
	}
	values := [3]int{}
	for i, part := range parts {
		parsed, err := strconv.Atoi(part)
		if err != nil || parsed < 0 {
			return semanticVersion{}, false
		}
		values[i] = parsed
	}
	return semanticVersion{major: values[0], minor: values[1], patch: values[2]}, true
}

func (v semanticVersion) greater(other semanticVersion) bool {
	if v.major != other.major {
		return v.major > other.major
	}
	if v.minor != other.minor {
		return v.minor > other.minor
	}
	return v.patch > other.patch
}

func dereferenceTag(ctx context.Context, client httpClient, apiBase, repository string, object gitObject) (string, error) {
	for range 8 {
		switch object.Type {
		case "commit":
			if len(object.SHA) != 40 {
				return "", fmt.Errorf("invalid commit SHA %q", object.SHA)
			}
			return strings.ToLower(object.SHA), nil
		case "tag":
			endpoint := strings.TrimRight(apiBase, "/") + "/repos/" + repository + "/git/tags/" + url.PathEscape(object.SHA)
			data, _, err := client.get(ctx, endpoint)
			if err != nil {
				return "", err
			}
			var tag struct {
				Object gitObject `json:"object"`
			}
			if err := json.Unmarshal(data, &tag); err != nil {
				return "", fmt.Errorf("decode annotated tag: %w", err)
			}
			object = tag.Object
		default:
			return "", fmt.Errorf("tag points to unsupported object type %q", object.Type)
		}
	}
	return "", errors.New("annotated tag chain exceeds 8 objects")
}

func actionRuntime(ctx context.Context, client httpClient, rawBase, repository, subpath, sha string) (string, error) {
	base := strings.TrimRight(rawBase, "/") + "/" + repository + "/" + sha + "/"
	if subpath != "" {
		base += strings.Trim(subpath, "/") + "/"
	}
	var lastErr error
	for _, filename := range []string{"action.yml", "action.yaml"} {
		data, _, err := client.get(ctx, base+filename)
		if err != nil {
			lastErr = err
			continue
		}
		var document struct {
			Runs struct {
				Using string `yaml:"using"`
			} `yaml:"runs"`
		}
		if err := yaml.Unmarshal(data, &document); err != nil {
			return "", fmt.Errorf("decode %s: %w", filename, err)
		}
		if document.Runs.Using == "" {
			return "", fmt.Errorf("%s has no runs.using", filename)
		}
		return strings.ToLower(document.Runs.Using), nil
	}
	return "", lastErr
}
