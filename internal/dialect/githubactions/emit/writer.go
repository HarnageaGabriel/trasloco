// workflowHeaderComment is the fixed first comment line of every emitted
// workflow file (docs/spec/emit-gha.md 4.1 rule 1).
const workflowHeaderComment = "# Generated by trasloco. Review before enabling."

// fileWriter accumulates one emitted workflow document together with its
// output elements, in file traversal order (docs/spec/emit-gha.md 2.3). Every
// primitive takes the qualified node ID the written element belongs to.
type fileWriter struct {
	path     string
	workflow model.Workflow
	jobKeys  []model.Pair
	elements []OutputElement
	defect   error
}

// newFileWriter starts one output file at path, the repository-relative
// workflow path.
func newFileWriter(path string) *fileWriter {
	return &fileWriter{path: path}
}

// pointer is the output-element path of one document position: the file path
// plus a JSON Pointer (RFC 6901) into the document, joined by "#".
func (w *fileWriter) pointer(pointer string) string {
	return w.path + "#" + pointer
}

// record appends one output element written for nodeID at the given JSON
// Pointer.
func (w *fileWriter) record(nodeID, pointer string) {
	w.elements = append(w.elements, OutputElement{Path: w.pointer(pointer), NodeID: nodeID})
}

// writeName records the workflow name for the pipeline node (5.1). A caller
// never records an empty name: the key is omitted.
func (w *fileWriter) writeName(nodeID, name string) {
	w.workflow.Name = name
	w.record(nodeID, "/name")
}

// writeWorkflowDispatch records the synthesized single event for a document
// with no push or pull_request trigger left (5.2 rule 2).
func (w *fileWriter) writeWorkflowDispatch(nodeID string) {
	w.workflow.On = model.Map(model.Pair{Key: "workflow_dispatch", Value: model.Null()})
	w.record(nodeID, "/on")
	w.record(nodeID, "/on/workflow_dispatch")
}

// writeWorkflowPermissions records the mandatory deny-all mapping (INV-02).
func (w *fileWriter) writeWorkflowPermissions(nodeID string) {
	w.workflow.Permissions = model.EmptyMap()
	w.record(nodeID, "/permissions")
}

// startJobs records the jobs mapping for the pipeline node.
func (w *fileWriter) startJobs(nodeID string) {
	w.jobKeys = nil
	w.record(nodeID, "/jobs")
}

// writePlaceholderJob attaches the failing placeholder of emit-gha.md 2.5 for
// one job: the job key, name, needs, runs-on, permission mapping, and one
// step placeholder named manual conversion required. code is the diagnostic
// code of the placeholder run text. sourceLine is the start line of the job
// origin; zero writes no comment. Every element belongs to the placeholder
// job.
func (w *fileWriter) writePlaceholderJob(nodeID, jobKey string, job model.Job, code string, sourceLine int) {
	job.Permissions = model.EmptyMap()
	step := model.Step{
		Name:  "Manual conversion required",
		Shell: "bash",
		Run: "echo \"::error::trasloco: manual conversion required (" + code + ")\"\n" +
			"exit 1\n",
	}
	item, err := encodeStruct(step)
	if err != nil {
		w.defect = err
		return
	}
	// The head comment is attached after the job is encoded: encodeStruct
	// re-encodes node fields and would drop it.
	job.Steps = nil

	base := "/jobs/" + pointerEscape(jobKey)
	w.record(nodeID, base)
	if job.Name != "" {
		w.record(nodeID, base+"/name")
	}
	w.record(nodeID, base+"/permissions")
	if len(job.Needs) > 0 {
		w.record(nodeID, base+"/needs")
	}
	w.record(nodeID, base+"/runs-on")
	w.record(nodeID, base+"/steps")
	w.record(nodeID, base+"/steps/0")
	w.record(nodeID, base+"/steps/0/name")
	w.record(nodeID, base+"/steps/0/shell")
	w.record(nodeID, base+"/steps/0/run")
	jobNode, err := encodeStruct(job)
	if err != nil {
		w.defect = err
		return
	}
	if sourceLine > 0 {
		item.HeadComment = "# trasloco: " + code + " (source line " + fmt.Sprint(sourceLine) + ")"
	}
	jobNode.Content = append(jobNode.Content,
		&goyaml.Node{Kind: goyaml.ScalarNode, Tag: "!!str", Value: "steps"},
		model.Seq(item))
	w.jobKeys = append(w.jobKeys, model.Pair{Key: jobKey, Value: jobNode})
}

// finalize assembles the document in fixed key order (4.1), applies the
// scalar and key styles of 4.2 (INV-07) and the fixed header comment, and
// encodes with a two-space indent, LF line endings, no BOM and exactly one
// trailing LF (INV-01). The produced bytes are re-parsed before they are
// returned.
func (w *fileWriter) finalize() ([]byte, []OutputElement, error) {
	if w.defect != nil {
		return nil, nil, fmt.Errorf("assemble workflow: %w", w.defect)
	}
	// The jobs mapping is attached after the workflow is encoded: encodeStruct
	// re-encodes node fields and would drop the comments set inside the jobs.
	w.workflow.Jobs = nil
	root, err := encodeStruct(w.workflow)
	if err != nil {
		return nil, nil, fmt.Errorf("assemble workflow: %w", err)
	}
	root.Content = append(root.Content,
		&goyaml.Node{Kind: goyaml.ScalarNode, Tag: "!!str", Value: "jobs"},
		model.Map(w.jobKeys...))
	root.HeadComment = workflowHeaderComment
	styleDocument(root)
	data, err := encodeDocument(root)
	if err != nil {
		return nil, nil, err
	}
	return data, w.elements, nil
}

// encodeStruct turns one fixed-structure value into a yaml node. Field order
// and yaml tags fix the output order; dynamic *yaml.Node fields keep their
// built order unchanged. A failure is an emitter defect (the model only holds
// encodable values, so this is unreachable by construction); it is returned,
// never swallowed.
func encodeStruct(value interface{}) (node *goyaml.Node, err error) {
	defer func() {
		if recovered := recover(); recovered != nil {
			node = nil
			err = fmt.Errorf("encode document fragment: %v", recovered)
		}
	}()
	var encoded goyaml.Node
	if err := encoded.Encode(value); err != nil {
		return nil, fmt.Errorf("encode document fragment: %w", err)
	}
	return &encoded, nil
}

// encodeDocument encodes one document root and re-parses the bytes before
// they are returned. The encoder never emits a BOM or a carriage return, and
// finalize checks that the file ends with exactly one LF (INV-01).
func encodeDocument(root *goyaml.Node) ([]byte, error) {
	var output bytes.Buffer
	encoder := goyaml.NewEncoder(&output)
	encoder.SetIndent(2)
	if err := encoder.Encode(root); err != nil {
		return nil, fmt.Errorf("encode workflow: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("close workflow encoder: %w", err)
	}
	data := output.Bytes()
	if bytes.HasPrefix(data, []byte(bOM)) {
		return nil, fmt.Errorf("encode workflow: output has a BOM")
	}
	if trimmed := bytes.TrimRight(data, "\n"); len(data)-len(trimmed) != 1 {
		return nil, fmt.Errorf("encode workflow: output ends with %d line feeds, want exactly 1",
			len(data)-len(trimmed))
	}
	document, findings := yamlx.Parse("workflow.yml", data)
	if document == nil || len(findings) > 0 || len(document.Documents) == 0 {
		return nil, fmt.Errorf("re-parse emitted workflow: not valid YAML")
	}
	return data, nil
}

// bOM is the UTF-8 byte order mark (INV-01).
const bOM = "\xEF\xBB\xBF"

// pointerEscape escapes one JSON Pointer reference token (RFC 6901): "~" as
// "~0", then "/" as "~1".
func pointerEscape(token string) string {
	token = strings.ReplaceAll(token, "~", "~0")
	return strings.ReplaceAll(token, "/", "~1")
}

// plainScalarPattern is the plain-style shape of emit-gha.md 4.2 rule 1.
var plainScalarPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_./@ -]*$`)

// yaml11PlainForbidden reports whether a case-folded scalar would be
// reinterpreted as a YAML 1.1 boolean, null or empty word (4.2 rule 1, INV-07).
func yaml11PlainForbidden(folded string) bool {
	switch folded {
	case "y", "n", "yes", "no", "on", "off", "true", "false", "null":
		return true
	}
	return false
}

// stringStyle picks the scalar style of one string value per 4.2 rules 1-4.
func stringStyle(value string) goyaml.Style {
	if plainScalarPattern.MatchString(value) &&
		!strings.HasSuffix(value, " ") &&
		!strings.Contains(value, "  ") &&
		!yaml11PlainForbidden(strings.ToLower(value)) {
		return 0
	}
	if hasControlRune(value) {
		return goyaml.DoubleQuotedStyle
	}
	if strings.Contains(value, "'") && !strings.ContainsAny(value, "\"\\") {
		return goyaml.DoubleQuotedStyle
	}
	return goyaml.SingleQuotedStyle
}

// hasControlRune reports whether the text has a control character or an
// explicit line-break character (4.2: any C0 control and DEL, plus NEL,
// U+2028 and U+2029, which the block rules also treat as line breaks).
func hasControlRune(value string) bool {
	for _, r := range value {
		if r <= 0x1F || r == 0x7F || r == 0x85 || r == 0x2028 || r == 0x2029 {
			return true
		}
	}
	return false
}

// runBlockStyle picks the literal block scalar of a run text (4.2; only run
// values use block scalars, everywhere else a line break falls to rule 4).
// The encoder derives the clip indicator (|, |- or |+) and the explicit
// indentation indicator 2 when the first line is empty or starts with a space.
func runBlockStyle(value string) goyaml.Style {
	for _, r := range value {
		if r == '\r' || r == 0x85 || r == 0x2028 || r == 0x2029 ||
			(r <= 0x1F && r != '\n' && r != '\t') || r == 0x7F {
			return goyaml.DoubleQuotedStyle
		}
	}
	return goyaml.LiteralStyle
}

// styleDocument applies emit-gha.md 4.2 to every key and string scalar of the
// assembled document (INV-07). documentRoot is true for the root mapping,
// where the workflow key "on" is the single plain-style exception.
func styleDocument(root *goyaml.Node) {
	styleTree(root, "", true)
}

// styleTree walks one document subtree. parentKey is the mapping key the
// current value is written under; only run values may become block scalars.
func styleTree(node *goyaml.Node, parentKey string, documentRoot bool) {
	switch node.Kind {
	case goyaml.MappingNode:
		for index := 0; index+1 < len(node.Content); index += 2 {
			key, value := node.Content[index], node.Content[index+1]
			if key.Kind == goyaml.ScalarNode && key.Tag == "!!str" {
				if documentRoot && key.Value == "on" {
					// The workflow key "on" is the single exception of 4.2
					// rule 1: GitHub requires it plain, and the YAML 1.1
					// boolean spelling makes the encoder quote it by default.
					key.Style = 0
				} else {
					key.Style = stringStyle(key.Value)
				}
			}
			styleTree(value, key.Value, false)
		}
	case goyaml.SequenceNode:
		for _, item := range node.Content {
			styleTree(item, parentKey, false)
		}
	default:
		styleScalar(node, parentKey)
	}
}

// styleScalar styles one leaf scalar. A string scalar is styled under 4.2; a
// run value with a line break becomes a literal block scalar; integers,
// booleans and null keep their plain representation (4.1 rule 4).
func styleScalar(node *goyaml.Node, parentKey string) {
	if node.Kind != goyaml.ScalarNode {
		return
	}
	if node.Tag != "!!str" {
		return
	}
	if parentKey == "run" && strings.Contains(node.Value, "\n") {
		node.Style = runBlockStyle(node.Value)
		return
	}
	node.Style = stringStyle(node.Value)
}
