func TestEmitStepVariants(t *testing.T) {
	jobNode, stepNode := mapping.QualifyID("job", "Job A"), mapping.QualifyID("step", "Job A", "step-1")
	cases := []struct {
		name        string
		fragment    mapping.StepFragment
		disposition string
		wantStep    string
		wantAbsent  string
	}{
		{
			name:        "placeholder",
			fragment:    mapping.StepFragment{Node: stepNode, JobID: "Job A", StepID: "step-1", Kind: mapping.StepPlaceholder, Code: "TRL-CONV-0003"},
			disposition: "placeholder",
			wantStep:    "echo \"::error::trasloco: manual conversion required (TRL-CONV-0003)\"",
		},
		{
			name:        "omit",
			fragment:    mapping.StepFragment{Node: stepNode, JobID: "Job A", StepID: "step-1", Kind: mapping.StepOmit},
			disposition: "dropped",
			wantAbsent:  "steps:",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dispatch := func(*ir.Pipeline) (mapping.Output, error) {
				return mapping.Output{
					Outcomes: []mapping.Outcome{claim(jobNode, "emitted"), claim(stepNode, tc.disposition)},
					Fragments: []mapping.Fragment{{
						Jobs:  []mapping.JobFragment{{Node: jobNode, JobID: "Job A"}},
						Steps: []mapping.StepFragment{tc.fragment},
					}},
				}, nil
			}
			got := emitMapped(samplePipeline(), stubNaming{}, Options{}, nil, dispatch)
			if len(got.Files) != 1 {
				t.Fatalf("files = %d, want 1 (diagnostics: %v)", len(got.Files), got.Diagnostics)
			}
			data := string(got.Files[0].Data)
			if tc.wantStep != "" && !strings.Contains(data, tc.wantStep) {
				t.Errorf("missing placeholder text:\n%s", data)
			}
			if tc.wantAbsent != "" && strings.Contains(data, tc.wantAbsent) {
				t.Errorf("omitted step still rendered:\n%s", data)
			}
		})
	}
}

