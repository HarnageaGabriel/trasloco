// fakeDispatch returns a dispatch that claims the given outcomes.
func fakeDispatch(outcomes ...mapping.Outcome) func(*ir.Pipeline) (mapping.Output, error) {
	return func(*ir.Pipeline) (mapping.Output, error) {
		return mapping.Output{Outcomes: outcomes}, nil
	}
}

func claim(id, kind string) mapping.Outcome {
	return mapping.Outcome{Disposition: mapping.Disposition{ID: id, Kind: kind, Fidelity: diag.FidelityApproximated}}
}

func TestEmitWithoutMappersIsUnchanged(t *testing.T) {
	want := Emit(samplePipeline(), catalog.ActionsLock{}, stubNaming{}, Options{}, nil)
	got := emitMapped(samplePipeline(), stubNaming{}, Options{}, nil, fakeDispatch())
	if len(want.Files) != 1 || len(got.Files) != 1 || !bytes.Equal(want.Files[0].Data, got.Files[0].Data) {
		t.Fatal("an empty dispatch changed the emitted file")
	}
	if len(want.Dispositions) != len(got.Dispositions) {
		t.Errorf("disposition count %d, want %d", len(got.Dispositions), len(want.Dispositions))
	}
}

func TestEmitAppliesMapperOutcome(t *testing.T) {
	id := mapping.QualifyID("trigger", "tr1")
	got := emitMapped(samplePipeline(), stubNaming{}, Options{}, nil, fakeDispatch(claim(id, "default")))
	for _, disposition := range got.Dispositions {
		if disposition.ID == id {
			if disposition.Kind != DispositionDefault || disposition.Fidelity != diag.FidelityApproximated {
				t.Errorf("disposition = %+v, want the mapper outcome", disposition)
			}
			return
		}
	}
	t.Fatalf("no disposition for %q", id)
}

