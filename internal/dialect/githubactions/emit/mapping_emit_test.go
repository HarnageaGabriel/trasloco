func TestEmitRendersMapperFragments(t *testing.T) {
	jobNode, stepNode := mapping.QualifyID("job", "Job A"), mapping.QualifyID("step", "Job A", "step-1")
	fragment := mapping.Fragment{
		Jobs: []mapping.JobFragment{{Node: jobNode, JobID: "Job A", Job: model.Job{RunsOn: "ubuntu-24.04"}}},
		Steps: []mapping.StepFragment{{
			Node: stepNode, JobID: "Job A", StepID: "step-1", Step: model.Step{Run: "make test\n"},
		}},
	}
	dispatch := func(*ir.Pipeline) (mapping.Output, error) {
		return mapping.Output{
			Outcomes:  []mapping.Outcome{claim(jobNode, "emitted"), claim(stepNode, "emitted")},
			Fragments: []mapping.Fragment{fragment},
		}, nil
	}
	got := emitMapped(samplePipeline(), stubNaming{}, Options{}, nil, dispatch)
	if len(got.Files) != 1 {
		t.Fatalf("files = %d, want 1 (diagnostics: %v)", len(got.Files), got.Diagnostics)
	}
	want := "# Generated by trasloco. Review before enabling.\n" +
		"name: Build and Test\non:\n  workflow_dispatch:\npermissions: {}\njobs:\n  Job A:\n" +
		"    permissions: {}\n    runs-on: ubuntu-24.04\n    steps:\n      - run: |\n          make test\n"
	if string(got.Files[0].Data) != want {
		t.Errorf("file mismatch:\n%s\nwant:\n%s", got.Files[0].Data, want)
	}
	var root goyaml.Node
	if err := goyaml.Unmarshal(got.Files[0].Data, &root); err != nil {
		t.Fatal(err)
	}
	owners := map[string]bool{}
	for _, element := range got.OutputElements {
		_, pointer, _ := strings.Cut(element.Path, "#")
		if _, ok := resolvePointer(&root, pointer); !ok {
			t.Errorf("pointer %q does not resolve", pointer)
		}
		owners[element.NodeID+" "+pointer] = true
	}
	for _, key := range []string{stepNode + " /jobs/Job A/steps/0/run", jobNode + " /jobs/Job A/runs-on"} {
		if !owners[key] {
			t.Errorf("missing element %q", key)
		}
	}
}

// elementOwners indexes the output elements by node ID and pointer.
func elementOwners(t *testing.T, got Result) map[string]bool {
	t.Helper()
	var root goyaml.Node
	if len(got.Files) != 1 {
		t.Fatalf("files = %d, want 1 (diagnostics: %v)", len(got.Files), got.Diagnostics)
	}
	if err := goyaml.Unmarshal(got.Files[0].Data, &root); err != nil {
		t.Fatal(err)
	}
	owners := map[string]bool{}
	for _, element := range got.OutputElements {
		_, pointer, _ := strings.Cut(element.Path, "#")
		if _, ok := resolvePointer(&root, pointer); !ok {
			t.Errorf("pointer %q does not resolve", pointer)
		}
		owners[element.NodeID+" "+pointer] = true
	}
	return owners
}

func TestEmitMergesMapEntriesPerKey(t *testing.T) {
	jobNode := mapping.QualifyID("job", "Job A")
	triggerNode := mapping.QualifyID("trigger", "tr1")
	fooNode := mapping.QualifyID("variable", "pipeline:ci", "0", "FOO")
	barNode := mapping.QualifyID("variable", "job:Job A", "0", "BAR")
	fragments := []mapping.Fragment{
		{Workflow: []mapping.WorkflowFragment{{On: []mapping.Entry{
			{Node: triggerNode, Key: "push", Value: model.EmptyMap()},
		}}}},
		{Jobs: []mapping.JobFragment{{Node: jobNode, JobID: "Job A", Env: []mapping.Entry{
			{Node: fooNode, Key: "FOO", Value: model.String("1")},
		}}}},
		{Jobs: []mapping.JobFragment{{Node: jobNode, JobID: "Job A", Env: []mapping.Entry{
			{Node: barNode, Key: "BAR", Value: model.String("2")},
		}}}},
	}
	dispatch := func(*ir.Pipeline) (mapping.Output, error) {
		return mapping.Output{
			Outcomes: []mapping.Outcome{
				claim(triggerNode, "emitted"), claim(jobNode, "emitted"),
				claim(fooNode, "emitted"), claim(barNode, "emitted"),
			},
			Fragments: fragments,
		}, nil
	}
	got := emitMapped(samplePipeline(), stubNaming{}, Options{}, nil, dispatch)
	owners := elementOwners(t, got)
	want := "# Generated by trasloco. Review before enabling.\n" +
		"name: Build and Test\non:\n  push: {}\npermissions: {}\njobs:\n  Job A:\n" +
		"    permissions: {}\n    runs-on: ubuntu-24.04\n    env:\n      FOO: '1'\n      BAR: '2'\n" +
		"    steps:\n      - name: Manual conversion required\n        shell: bash\n        run: |\n" +
		"          echo \"::error::trasloco: manual conversion required (TRL-CONV-0003)\"\n          exit 1\n"
	if string(got.Files[0].Data) != want {
		t.Errorf("file mismatch:\n%s\nwant:\n%s", got.Files[0].Data, want)
	}
	for _, key := range []string{
		mapping.QualifyID("pipeline", "ci") + " /on",
		triggerNode + " /on/push",
		jobNode + " /jobs/Job A/env",
		fooNode + " /jobs/Job A/env/FOO",
		barNode + " /jobs/Job A/env/BAR",
	} {
		if !owners[key] {
			t.Errorf("missing element %q", key)
		}
	}
}

